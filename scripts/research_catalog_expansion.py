"""Incremental theory-library expansion packs.

This module is intentionally separate from ``build_research_catalog.py``.
The attached scan confirms the chapter titles and starting pages for the
Management and Organization 60 book, but it is image-only and has not yet
been OCR-checked chapter by chapter.  Those records therefore carry an
explicit ``book_scan_scaffold`` status.  The cross-business-school additions
are curated navigation scaffolds with pending source verification; they are
not presented as a completed literature review.
"""

PENDING = 'pending_verification'
SCAFFOLD = 'curated_scaffold'
BOOK_SCAFFOLD = 'book_scan_scaffold'


def W(authors, year, title, venue, kind='origin'):
    return {
        'authors': authors, 'year': year, 'title': title, 'venue': venue,
        'kind': kind, 'doi': None, 'openalex_id': None, 'cited_by_count': None,
        'verification': PENDING,
    }


def C(id, name, name_zh, en, zh, disc, kw, theories, roles,
      source_status=SCAFFOLD, source_pack=None):
    item = {
        'id': id, 'name': name, 'name_zh': name_zh,
        'definition': en, 'definition_zh': zh,
        'discipline': list(disc), 'keywords': list(kw),
        'related_theories': list(theories), 'roles': list(roles),
        'antecedents': [], 'outcomes': [], 'mediators': [], 'moderators': [],
        'measurement_scales': [{
            'name': name + ' scale metadata',
            'authors': 'Not loaded; verify against the primary source',
            'year': None, 'items': None, 'response_scale': 'Not loaded',
            'original_paper': None, 'example_items': [],
            'source_status': PENDING,
        }],
        'source_status': source_status,
    }
    if source_pack:
        item['source_pack'] = source_pack
    return item


def X(id, name, name_zh, abbreviation, disc, year, en, zh,
      tags=(), kw=(), core=(), ante=(), mech=(), out=(), mod=(),
      bc=(), crit=(), apps=(), rel=(), works=(), source_status=SCAFFOLD,
      source_pack=None, source_page=None, source_note=None):
    item = {
        'id': id, 'name': name, 'name_zh': name_zh, 'abbreviation': abbreviation,
        'definition': en, 'definition_zh': zh,
        'discipline': list(disc), 'origin_year': year,
        'tags': list(tags), 'broad_tags': [], 'keywords': list(kw),
        'core_constructs': list(core), 'antecedents': list(ante),
        'mechanisms': list(mech), 'outcomes': list(out),
        'moderators': list(mod),
        'boundary_conditions': list(bc) or [
            'Specify the unit of analysis, assumptions, and context before applying this scaffold to a study.'
        ],
        'criticisms': list(crit) or [
            'This is a curated navigation record; verify theory-specific boundary conditions and measures against primary sources.'
        ],
        'applications': list(apps),
        'related_theories': list(rel), 'seminal_works': list(works),
        'key_scholars': [], 'source_status': source_status,
    }
    if source_pack:
        item['source_pack'] = source_pack
    if source_page is not None:
        item['source_page'] = source_page
    if source_note:
        item['source_note'] = source_note
    return item


