@dataclass
class Section:
    """One document section: a heading (optional) plus its body paragraphs."""
    title: str
    level: int
    paragraphs: list[str] = field(default_factory=list)

    @property
    def body(self) -> str:
        return '\n'.join(p for p in self.paragraphs if p.strip())

    @property
    def chars(self) -> int:
        return len(self.title) + len(self.body)

    @property
    def is_empty(self) -> bool:
        return not self.title.strip() and not self.body.strip()


def _pdf_unit_text(unit) -> str:
    return ' '.join(seg.core_text.strip() for seg in unit.segments if seg.core_text.strip())


def extract_document_blocks(input_path: Path, audit: dict | None = None) -> list[tuple[int, str]]:
    """Return ordered (heading_level, text) blocks; level 0 = body paragraph.

    Shares the translation extractors, but DOCX summaries deliberately include
    only ``word/document.xml``.  Headers, footers, comments, footnotes, and
    endnotes may be appropriate translation targets but are not article body.
    """
    extension = input_path.suffix.casefold()
    blocks: list[tuple[int, str]] = []
    extraction_audit = audit if audit is not None else {}
    extraction_audit['input_type'] = extension.lstrip('.')
    if extension == '.docx':
        _parts, units, package_audit = extract_docx_units(input_path, preserve_references=True)
        body_units = [unit for unit in units if unit.part_name == 'word/document.xml']
        extraction_audit['docx_non_body_units_excluded'] = len(units) - len(body_units)
        extraction_audit['extractor_skipped'] = dict(package_audit.get('skipped') or {})
        for unit in body_units:
            text = _paragraph_plain_text(unit.paragraph_xml).strip()
            if not text:
                continue
            level = _heading_level(unit.paragraph_xml)
            blocks.append((level if level and 1 <= level <= 6 else 0, text))
    elif extension == '.pdf':
        try:
            units, bundle = extract_pdf_units(input_path, preserve_references=True)
        except PdfFormatError as exc:
            raise TranslationError(str(exc)) from exc
        extraction_audit.update({
            'pdf_page_count': len(bundle.page_sizes),
            'pdf_tables_detected': sum(bundle.table_counts),
            'extractor_skipped': dict(bundle.skipped),
        })
        for unit in units:
            text = _pdf_unit_text(unit)
            if not text:
                continue
            region = bundle.regions.get(unit.unit_id)
            blocks.append((1 if (region and region.heading) else 0, text))
    elif extension in {'.txt', '.md'}:
        raw = input_path.read_bytes()
        try:
            text = raw.decode('utf-8-sig')
        except UnicodeDecodeError as exc:
            raise TranslationError('TXT/Markdown 必须使用 UTF-8 编码') from exc
        # 逐行识别:markdown 标题即便紧跟正文(无空行)也要断成独立标题块。
        paragraph: list[str] = []

        def flush() -> None:
            joined = '\n'.join(paragraph).strip()
            if joined:
                blocks.append((0, joined))
            paragraph.clear()

        for line in text.splitlines():
            heading = _MD_HEADING_RE.match(line.strip())
            if heading:
                flush()
                blocks.append((len(heading.group(1)), heading.group(2)))
            elif not line.strip():
                flush()
            else:
                paragraph.append(line)
        flush()
    else:
        raise TranslationError('总结当前仅支持 PDF、DOCX、TXT 和 Markdown')
    extraction_audit['block_count'] = len(blocks)
    extraction_audit['block_characters'] = sum(len(text) for _level, text in blocks)
    return blocks


def group_sections(blocks: list[tuple[int, str]]) -> list[Section]:
    """Split ordered blocks into sections at each heading.

    Body content appearing before the first heading becomes an opening section.
    """
    sections: list[Section] = []
    current = Section(title='', level=0)
    for level, text in blocks:
        if level >= 1:
            if not current.is_empty:
                sections.append(current)
            current = Section(title=text, level=level)
        else:
            current.paragraphs.append(text)
    if not current.is_empty:
        sections.append(current)
    if not sections:
        raise TranslationError('未从文档中提取到可总结的正文')
    if len(sections) > SUMMARY_MAX_SECTIONS:
        raise TranslationError(
            f'检测到 {len(sections)} 个章节，超过安全上限 {SUMMARY_MAX_SECTIONS}；'
            '为避免静默截断，任务已停止。')
    return sections


def _split_text_to_budget(text: str, budget: int) -> list[str]:
    """Split even a single oversized paragraph without silently exceeding budget."""
    remaining = text.strip()
    pieces: list[str] = []
    while len(remaining) > budget:
        prefix = remaining[:budget]
        minimum = max(1, budget // 2)
        boundaries = [
            match.end() for match in re.finditer(r'[。！？.!?][\"”’\)\]]*\s*|\s+', prefix)
            if match.end() >= minimum
        ]
        cut = boundaries[-1] if boundaries else budget
        piece = remaining[:cut].strip()
        if not piece:
            piece, cut = remaining[:budget], budget
        pieces.append(piece)
        remaining = remaining[cut:].strip()
    if remaining:
        pieces.append(remaining)
    return pieces


def _append_question_evidence(rows: list[dict], text: str, title: str,
                              locator: str, page_number: int | None = None) -> None:
    """Append bounded, source-hashed evidence chunks without silent truncation."""
    for piece in _split_text_to_budget(text, QUESTION_EVIDENCE_CHAR_BUDGET):
        if not piece.strip():
            continue
        chunk_id = f'E{len(rows) + 1:04d}'
        rows.append({
            'evidence_id': chunk_id,
            'title': title.strip() or '正文',
            'locator': locator,
            'page_number': page_number,
            'text': piece.strip(),
            'source_sha256': hashlib.sha256(
                piece.strip().encode('utf-8')).hexdigest(),
        })


def extract_question_evidence(input_path: Path) -> list[dict]:
    """Extract bounded original-language evidence with user-visible locations.

    Question answering deliberately grounds itself in the source document, not
    in a generated translation or summary. PDF chunks retain page numbers;
    DOCX/TXT/Markdown chunks retain the nearest section heading or paragraph
    position. Reference lists are excluded as claim evidence.
    """
    extension = input_path.suffix.casefold()
    rows: list[dict] = []
    current_title = ''
    if extension == '.pdf':
        try:
            units, bundle = extract_pdf_units(input_path, preserve_references=True)
        except PdfFormatError as exc:
            raise TranslationError(str(exc)) from exc
        for unit in units:
            text = _pdf_unit_text(unit).strip()
            if not text:
                continue
            region = bundle.regions.get(unit.unit_id)
            if region and region.heading:
                if _REFERENCE_TITLE_RE.fullmatch(text):
                    break
                current_title = text
                continue
            page_number = int(unit.page_index) + 1
            locator = f'第 {page_number} 页'
            if current_title:
                locator += f' · {current_title}'
            _append_question_evidence(
                rows, text, current_title or '正文', locator, page_number)
    elif extension == '.docx':
        _parts, units, _audit = extract_docx_units(
            input_path, preserve_references=True)
        paragraph_index = 0
        for unit in units:
            if unit.part_name != 'word/document.xml':
                continue
            text = _paragraph_plain_text(unit.paragraph_xml).strip()
            if not text:
                continue
            level = _heading_level(unit.paragraph_xml)
            if level:
                if _REFERENCE_TITLE_RE.fullmatch(text):
                    break
                current_title = text
                continue
            paragraph_index += 1
            locator = current_title or f'正文第 {paragraph_index} 段'
            _append_question_evidence(
                rows, text, current_title or '正文', locator)
    elif extension in {'.txt', '.md'}:
        blocks = extract_document_blocks(input_path)
        paragraph_index = 0
        for level, text in blocks:
            if level:
                if _REFERENCE_TITLE_RE.fullmatch(text):
                    break
                current_title = text
                continue
            paragraph_index += 1
            locator = current_title or f'正文第 {paragraph_index} 段'
            _append_question_evidence(
                rows, text, current_title or '正文', locator)
    else:
        raise TranslationError('文章问答当前仅支持 PDF、DOCX、TXT 和 Markdown')
    if not rows:
        raise TranslationError('未从原文中提取到可用于回答问题的正文证据')
    return rows


def _question_terms(text: str, expand_concepts: bool = False) -> set[str]:
    """Return compact English tokens plus CJK bigrams for local retrieval."""
    folded = (text or '').casefold()
    terms = set(re.findall(r'[a-z][a-z0-9_-]{1,}|\d+(?:\.\d+)?', folded))
    for run in re.findall(r'[\u3400-\u9fff]+', folded):
        if len(run) == 1:
            terms.add(run)
        else:
            terms.update(run[index:index + 2] for index in range(len(run) - 1))
    # Questions are commonly asked in Chinese about English papers. Expand only
    # a bounded set of high-value academic concepts; this is retrieval support,
    # not a claim-level translation or an ontology.
    concept_groups = (
        (('样本', '樣本', 'sample', 'participants'), ('sample', 'participant', 'participants')),
        (('访谈', '訪談', 'interview'), ('interview', 'interviews')),
        (('因果', 'causal', 'causality'), ('causal', 'causality', 'association')),
        (('相关', '相關', 'association', 'correlation'), ('association', 'correlation')),
        (('测量', '測量', 'measure', 'measurement'), ('measure', 'measurement', 'scale')),
        (('方法', 'method', 'methodology'), (
            'method', 'methods', 'methodology', 'model', 'models', 'modeling',
            'modelling', 'simulation', 'simulations', 'agent-based', 'abm',
            'reinforcement', 'learning', 'agent', 'agents', 'task', 'tasks',
            'choice', 'choices', 'decision', 'decisions', 'feedback', 'parameter',
            'parameters', 'procedure', 'procedures', 'specification',
        )),
        (('数据', '資料', 'data'), ('data', 'dataset')),
        (('结果', '結果', '发现', '發現', 'result', 'finding'),
         ('result', 'results', 'finding', 'findings')),
        (('理论', '理論', 'theory'), ('theory', 'theoretical')),
        (('变量', '變量', '變數', 'variable'), ('variable', 'variables', 'construct')),
        (('假设', '假設', 'hypothesis'), ('hypothesis', 'hypotheses')),
        (('局限', '限制', 'limitation'), ('limitation', 'limitations')),
    )
    if expand_concepts:
        for triggers, expansions in concept_groups:
            if any(trigger in folded for trigger in triggers):
                terms.update(expansions)
    return terms


def rank_question_evidence(evidence: list[dict], query: str,
                           limit: int = QUESTION_MAX_EVIDENCE,
                           context: str = '') -> list[dict]:
    """Rank evidence locally and retain section diversity.

    This is intentionally deterministic and dependency-free. The language model
    only receives the selected original chunks and cannot silently search a
    generated summary instead.
    """
    if not evidence:
        return []
    query_terms = _question_terms(query, expand_concepts=True)
    # Previous user turns can resolve terse follow-ups (for example, "what about
    # that method?") but must not outweigh a new question on another topic.
    # Keeping the two term sets separate prevents an earlier query from pinning
    # every later turn to the same evidence blocks.
    context_terms = _question_terms(context, expand_concepts=True) - query_terms
    retrieval_terms = query_terms | context_terms
    chunk_terms = [_question_terms(row.get('text', '')) for row in evidence]
    document_frequency = {
        term: sum(1 for terms in chunk_terms if term in terms)
        for term in retrieval_terms
    }
    structural_re = re.compile(
        r'abstract|摘要|引言|introduction|method|方法|data|数据|資料|'
        r'result|finding|结果|結果|发现|發現|discussion|讨论|討論|'
        r'conclusion|结论|結論', re.I)
    ranked = []
    total = len(evidence)
    for index, (row, terms) in enumerate(zip(evidence, chunk_terms)):
        overlap_score = 0.0
        for term in query_terms & terms:
            overlap_score += 1.0 + max(
                0.0, (total - document_frequency.get(term, total)) / max(total, 1))
        for term in context_terms & terms:
            overlap_score += 0.30 * (1.0 + max(
                0.0, (total - document_frequency.get(term, total)) / max(total, 1)))
        title_terms = _question_terms(row.get('title', ''))
        title_score = (1.5 * len(query_terms & title_terms)
                       + 0.35 * len(context_terms & title_terms))
        structural_score = 0.2 if structural_re.search(row.get('title', '')) else 0.0
        ranked.append((overlap_score + title_score + structural_score, -index, row))
    ranked.sort(key=lambda item: (item[0], item[1]), reverse=True)

    selected: list[dict] = []
    per_title: dict[str, int] = {}
    for score, _neg_index, row in ranked:
        title = row.get('title') or row.get('locator') or '正文'
        if per_title.get(title, 0) >= 2 and len(selected) < min(limit, 3):
            continue
        item = dict(row)
        item['retrieval_score'] = round(score, 4)
        selected.append(item)
        per_title[title] = per_title.get(title, 0) + 1
        if len(selected) >= max(1, min(limit, QUESTION_MAX_EVIDENCE)):
            break
    return selected


def _section_units(sections: list[Section], opening_label: str = '(开头)') -> list[dict]:
    """Flatten body-bearing sections into bounded model units.

    A heading with no body is metadata, not evidence.  It is therefore excluded
    rather than asking the model to infer a 2-4 sentence summary from a title.
    """
    units: list[dict] = []
    for index, section in enumerate(sections):
        body = section.body.strip()
        if not body:
            continue
        label = section.title.strip() or opening_label
        text_budget = max(800, SUMMARY_SECTION_CHAR_BUDGET - min(len(label), 400))
        paragraph_pieces: list[str] = []
        for paragraph in section.paragraphs:
            if paragraph.strip():
                paragraph_pieces.extend(_split_text_to_budget(paragraph, text_budget))

        chunks: list[str] = []
        current: list[str] = []
        current_chars = 0
        for piece in paragraph_pieces:
            separator_chars = 1 if current else 0
            if current and current_chars + separator_chars + len(piece) > text_budget:
                chunks.append('\n'.join(current))
                current, current_chars = [], 0
                separator_chars = 0
            current.append(piece)
            current_chars += separator_chars + len(piece)
        if current:
            chunks.append('\n'.join(current))
        for part, text in enumerate(chunks):
            if len(text) > text_budget:
                raise TranslationError('总结分段超过上下文安全预算，任务已停止')
            units.append({'section_index': index, 'part': part, 'parts': len(chunks),
                          'title': label, 'text': text})
    return units


def summary_unit_sha256(unit: dict, options: dict) -> str:
    """Bind a cached summary to exact source text, options, and prompt version."""
    payload = {
        'schema_version': SUMMARY_CHECKPOINT_SCHEMA_VERSION,
        'prompt_version': SUMMARY_PROMPT_VERSION,
        'title': unit.get('title', ''),
        'text': unit.get('text', ''),
        'target_language': options.get('target_language', ''),
        'domain': options.get('domain', ''),
        'glossary': options.get('glossary') or [],
    }
    raw = json.dumps(payload, ensure_ascii=False, sort_keys=True,
                     separators=(',', ':')).encode('utf-8')
    return hashlib.sha256(raw).hexdigest()


def load_summary_checkpoint(path: Path) -> dict[str, dict[str, str]]:
    """Load only v2 records carrying a non-empty summary and a source hash."""
    restored: dict[str, dict[str, str]] = {}
    if not path.is_file():
        return restored
    for line in path.read_text(encoding='utf-8').splitlines():
        try:
            record = json.loads(line)
        except (json.JSONDecodeError, TypeError):
            continue
        if record.get('schema_version') != SUMMARY_CHECKPOINT_SCHEMA_VERSION:
            continue
        summaries = record.get('unit_summaries')
        hashes = record.get('source_sha256')
        if not isinstance(summaries, dict) or not isinstance(hashes, dict):
            continue
        for unit_id, summary in summaries.items():
            source_hash = hashes.get(unit_id)
            if (isinstance(unit_id, str) and isinstance(summary, str) and summary.strip()
                    and isinstance(source_hash, str)
                    and re.fullmatch(r'[0-9a-f]{64}', source_hash)):
                restored[unit_id] = {
                    'summary': summary.strip(), 'source_sha256': source_hash,
                }
    return restored


def _audit_summary_language(texts: list[str], target_language: str) -> dict:
    """Record a conservative script-ratio diagnostic without discarding output.

    Academic summaries legitimately contain acronyms, construct names, and
    quotations in another script.  A ratio is therefore an audit warning, not a
    destructive gate; structural completeness remains the hard requirement.
    """
    combined = '\n'.join(text for text in texts if isinstance(text, str))
    cjk_characters = len(re.findall(r'[\u3400-\u9fff]', combined))
    latin_characters = len(re.findall(r'[A-Za-z]', combined))
    checked_characters = cjk_characters + latin_characters
    folded = (target_language or '').casefold()
    if 'english' in folded or '英文' in target_language:
        expected_script, target_characters, minimum_ratio = (
            'latin', latin_characters, 0.80)
    elif ('chinese' in folded or '中文' in target_language
          or '繁體' in target_language or '繁体' in target_language):
        expected_script, target_characters, minimum_ratio = (
            'cjk', cjk_characters, 0.35)
    else:
        expected_script, target_characters, minimum_ratio = (
            'unknown', 0, None)

    ratio = (target_characters / checked_characters) if checked_characters else None
    if expected_script == 'unknown':
        status = 'not_applicable'
    elif checked_characters < 40:
        status = 'insufficient_text'
    else:
        status = 'pass' if ratio is not None and ratio >= minimum_ratio else 'warning'
    return {
        'target_language': target_language,
        'expected_script': expected_script,
        'status': status,
        'checked_characters': checked_characters,
        'cjk_characters': cjk_characters,
        'latin_characters': latin_characters,
        'target_script_ratio': round(ratio, 4) if ratio is not None else None,
        'minimum_ratio': minimum_ratio,
    }


def summarize_document(input_path: Path, client, options: dict,
                       progress=None, checkpoint=None,
                       resume: dict[str, dict[str, str]] | None = None) -> dict:
    """Run the two-layer summary. Returns section summaries + overall structured text.

    progress(done, total) is reported over section units so a per-file progress
    bar matches the translation flow.  checkpoint(record) persists each finished
    map batch so an interrupted job can resume without re-billing the GPU.
    """
    extraction_audit: dict = {}
    blocks = extract_document_blocks(input_path, audit=extraction_audit)
    sections = group_sections(blocks)
    labels = _summary_labels(options.get('target_language', ''))
    units = _section_units(sections, opening_label=f"({labels['opening']})")
    if not units:
        raise TranslationError('检测到标题，但没有提取到可总结的章节正文')
    total = len(units)
    resume = resume or {}

    unit_summaries: dict[str, str] = {}
    unit_hashes: dict[str, str] = {}
    pending = []
    for unit in units:
        key = f"{unit['section_index']}:{unit['part']}"
        unit['unit_id'] = key
        source_hash = summary_unit_sha256(unit, options)
        unit['source_sha256'] = source_hash
        unit_hashes[key] = source_hash
        cached = resume.get(key)
        if (isinstance(cached, dict) and cached.get('source_sha256') == source_hash
                and isinstance(cached.get('summary'), str) and cached['summary'].strip()):
            unit_summaries[key] = cached['summary'].strip()
        else:
            pending.append(unit)
    if progress:
        progress(len(unit_summaries), total)

    def on_batch(mapped: dict[str, str]) -> None:
        if not isinstance(mapped, dict) or any(
                unit_id not in unit_hashes or not isinstance(summary, str)
                or not summary.strip() for unit_id, summary in mapped.items()):
            raise TranslationError('模型返回的逐节小结结构无效')
        unit_summaries.update(mapped)
        if checkpoint:
            checkpoint({
                'schema_version': SUMMARY_CHECKPOINT_SCHEMA_VERSION,
                'prompt_version': SUMMARY_PROMPT_VERSION,
                'unit_summaries': mapped,
                'source_sha256': {unit_id: unit_hashes[unit_id] for unit_id in mapped},
            })
        if progress:
            progress(len(unit_summaries), total)

    if pending:
        client.summarize_sections(pending, options, on_batch)
    missing_unit_ids = sorted(set(unit_hashes) - set(unit_summaries))
    if missing_unit_ids:
        raise TranslationError(
            f'逐节小结不完整：缺少 {len(missing_unit_ids)} 个正文单元，任务已停止。')

    # Merge multi-part section summaries back in document order.
    section_summaries: list[dict] = []
    for index, section in enumerate(sections):
        parts = [unit_summaries.get(f'{index}:{p}', '')
                 for p in range(max(1, sum(1 for u in units if u['section_index'] == index)))]
        combined = ' '.join(part.strip() for part in parts if part.strip())
        if combined:
            section_summaries.append({
                'title': section.title.strip() or f"({labels['opening']})",
                'level': section.level or 1,
                'summary': combined,
            })

    overall = client.synthesize_overall(section_summaries, options) if section_summaries else ''
    if not isinstance(overall, str) or not overall.strip():
        raise TranslationError('全文摘要为空，任务已停止。')
    title_only = sum(1 for section in sections if section.title.strip() and not section.body.strip())
    language_audit = _audit_summary_language(
        [*unit_summaries.values(), overall], options.get('target_language', ''))
    extraction_audit.update({
        'sections_detected': len(sections),
        'title_only_sections_excluded': title_only,
        'section_count': len(section_summaries),
        'unit_count': total,
        'summarized_characters': sum(len(unit['text']) for unit in units),
        'maximum_unit_characters': max(len(unit['text']) for unit in units),
        'checkpoint_units_reused': total - len(pending),
        'checkpoint_schema_version': SUMMARY_CHECKPOINT_SCHEMA_VERSION,
        'prompt_version': SUMMARY_PROMPT_VERSION,
        'silent_truncation': False,
        'completeness_audit': {
            'status': 'pass',
            'expected_units': total,
            'completed_units': len(unit_summaries),
            'body_sections': len(section_summaries),
            'overall_summary_present': True,
        },
        'language_audit': language_audit,
    })
    return {'section_summaries': section_summaries, 'overall': overall,
            'section_count': len(section_summaries), 'unit_count': total,
            'audit': extraction_audit}


def _coverage_text(audit: dict, target_language: str) -> str:
    folded = (target_language or '').casefold()
    values = {
        'blocks': audit.get('block_count', 0),
        'units': audit.get('unit_count', 0),
        'titles': audit.get('title_only_sections_excluded', 0),
        'non_body': audit.get('docx_non_body_units_excluded', 0),
        'table_lines': (audit.get('extractor_skipped') or {}).get('table_lines', 0),
        'references': ((audit.get('extractor_skipped') or {}).get('reference_regions', 0)
                       + (audit.get('extractor_skipped') or {}).get('reference_paragraphs', 0)),
        'formulas': (audit.get('extractor_skipped') or {}).get('formula_paragraphs', 0),
    }
    language_audit = audit.get('language_audit') or {}
    language_status = language_audit.get('status', 'not_available')
    language_ratio = language_audit.get('target_script_ratio')
    ratio_text = (f'{language_ratio:.0%}' if isinstance(language_ratio, (int, float))
                  else 'n/a')
    if 'english' in folded or '英文' in target_language:
        return (f"{values['blocks']} extracted blocks; {values['units']} bounded summary units; "
                f"{values['titles']} title-only sections, {values['non_body']} non-body DOCX units, "
                f"{values['formulas']} formula paragraphs, {values['table_lines']} PDF table lines, "
                f"and {values['references']} reference "
                f"regions excluded; no silent section truncation; language audit "
                f"{language_status} (target-script ratio {ratio_text}).")
    if 'traditional' in folded or '繁體' in target_language or '繁体' in target_language:
        status_text = {
            'pass': '通過', 'warning': '警告', 'insufficient_text': '文字過短',
            'not_applicable': '不適用', 'not_available': '無資料',
        }.get(language_status, language_status)
        return (f"抽取 {values['blocks']} 個文字區塊並形成 {values['units']} 個限長單元；排除 "
                f"{values['titles']} 個僅標題章節、{values['non_body']} 個 DOCX 非正文單元、"
                f"{values['formulas']} 個公式段落、{values['table_lines']} 行 PDF 表格及 "
                f"{values['references']} 個參考文獻區域；"
                f"未靜默截斷章節；語言審計{status_text}（目標文字占比 {ratio_text}）。")
    status_text = {
        'pass': '通过', 'warning': '警告', 'insufficient_text': '文本过短',
        'not_applicable': '不适用', 'not_available': '无数据',
    }.get(language_status, language_status)
    return (f"抽取 {values['blocks']} 个文本块并形成 {values['units']} 个限长单元；排除 "
            f"{values['titles']} 个仅标题章节、{values['non_body']} 个 DOCX 非正文单元、"
            f"{values['formulas']} 个公式段落、{values['table_lines']} 行 PDF 表格及 "
            f"{values['references']} 个参考文献区域；"
            f"未静默截断章节；语言审计{status_text}（目标文字占比 {ratio_text}）。")


def render_summary_markdown(meta: dict, result: dict) -> str:
    """Render a localized, self-contained Markdown summary with coverage metadata."""
    target = meta.get('target_language', '')
    labels = _summary_labels(target)
    lines = [f"# {labels['title']} · {meta.get('original_filename', '')}", '']
    separator = labels.get('separator', '：')
    left_paren = labels.get('left_paren', '（')
    right_paren = labels.get('right_paren', '）')
    lines.append(f"- {labels['language']}{separator}{target}")
    lines.append(
        f"- {labels['model']}{separator}{meta.get('model', '')}"
        f"{left_paren}{labels['location']}{right_paren}")
    if meta.get('completed_at'):
        lines.append(f"- {labels['completed']}{separator}{meta['completed_at']}")
    lines.append(f"- {labels['sections']}{separator}{result.get('section_count', 0)}")
    lines.append(
        f"- {labels['coverage']}{separator}"
        f"{_coverage_text(result.get('audit') or {}, target)}")
    lines.append('')
    lines.append(f"## {labels['overall']}")
    lines.append('')
    lines.append(result.get('overall', '').strip() or labels['none'])
    lines.append('')
    lines.append(f"## {labels['section_summaries']}")
    lines.append('')
    for item in result.get('section_summaries', []):
        lines.append(f"### {item['title']}")
        lines.append('')
        lines.append(item['summary'].strip())
    lines.append('')
    lines.append('---')
    lines.append(labels['disclaimer'])
    return '\n'.join(lines).rstrip() + '\n'
